#!/usr/bin/env Rscript
source('R/enroute-level-exposure.R')
source('R/paper-window-references.R')
cfg <- paper_ref_config()
result <- build_paper_window_references(cfg)
dir.create(cfg$output,recursive=TRUE,showWarnings=FALSE)
saveRDS(result,file.path(cfg$output,'analysis.rds'))
for(n in c('flights','windows','events','candidates','availability'))
  arrow::write_parquet(result[[n]],file.path(cfg$output,paste0('restricted-',n,'.parquet')))
for(n in c('inventory','types','dates','support','grid','wide_grid','paired_support','paired_cells','overview','enroute_support','fuel_convention','profile_state'))
  readr::write_csv(result[[n]],file.path(cfg$output,paste0(n,'.csv')))
for(n in c('summary','paired_summary','band_summary','boundary_summary','support'))
  readr::write_csv(result$enroute[[n]],file.path(cfg$output,paste0('enroute-',n,'.csv')))
readr::write_csv(dplyr::select(cfg$manifest,-LOCAL_PATH),file.path(cfg$output,'input-manifest.csv'))
readr::write_csv(result$source_fingerprint,file.path(cfg$output,'source-manifest.csv'))
writeLines(capture.output(sessionInfo()),file.path(cfg$output,'session-info.txt'))
# Check again after building: adopted source inputs remain byte-identical.
invisible(paper_ref_config())
print(result$paired_support |>dplyr::filter(WINDOW%in%c(cfg$core_windows,cfg$terminal_options),METRIC=='FUEL_KG'),n=12)
cat('Restricted analysis:',cfg$output,'\n')
